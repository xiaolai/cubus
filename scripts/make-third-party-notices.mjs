#!/usr/bin/env node
// Generate apps/web/THIRD_PARTY_NOTICES.md: what ships with cubus, under which licence, from where.
//
//   pnpm notices            rewrite apps/web/THIRD_PARTY_NOTICES.md
//   pnpm notices --check    exit 1 if the committed file is not what would be generated now
//
// READ FROM THE SOURCES OF TRUTH, never typed in:
//   - the npm packages from what esbuild actually puts in every vendored bundle (its metafile, run
//     with each bundle's own build command), so a package a dependency pulls in is listed as surely
//     as one the entry imports; and the runtime copy-ort.mjs copies beside them;
//   - the Rust crates from `cargo metadata` and a `cargo tree --target all` of the desktop binary;
//   - the Android libraries from the Gradle lockfile of the app's release runtime classpath, which
//     the build enforces, and the licences their POMs declare (`scripts/android-licences.mjs`);
//   - the model's training data from the model card, the fixtures from ml/golden/SOURCES.json.
// A dependency this file does not know how to license stops the generator rather than being listed
// under a guess.
//
// EVERY PACKAGE'S OWN NOTICES. A licence like MIT requires that "the above copyright notice and
// this permission notice" travel with the software, and Apache-2.0 requires a NOTICE file's
// contents to. So each package's licence and notice files are reproduced as that package carries
// them, copyright lines and all, deduplicated only where two texts are identical. This file used
// to reproduce ONE text per licence taken from a single crate, and to name Cargo's `authors` as
// the copyright holders — which they are not: `bytes` names Carl Lerche in its licence and nowhere
// else, and `dpi`'s LICENSE-LIBM-MIT names holders its metadata never mentions.
//
// WHY THE FILE IS COMMITTED AND ALSO GENERATED. The web app has no build step that could produce
// it at deploy time, and the About card links it — so it is an artifact like the vendored bundles:
// generated by a script, committed, and gated. `--check` is that gate (ci.yml's supply-chain job);
// apps/web/test/third-party-notices.test.mjs tests the helpers exported below and holds the
// committed text to the bundles and the lockfiles without needing cargo.
//
// LICENCE CHOICE. A package offering "MIT OR Apache-2.0" is used under ONE alternative, and the
// file says which: the alternative whose licence texts the package itself carries, and among those
// the first by PREFERENCE. An `AND` binds every side, a `WITH` exception is part of its licence,
// and an expression with no accepted alternative is an error here, on purpose — a new licence in
// the tree is a decision, not a line item.

