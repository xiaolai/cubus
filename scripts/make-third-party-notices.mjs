// 1. The web app's bundled npm packages, from what esbuild puts in each bundle.

/** Each workspace package directory, from pnpm-workspace.yaml's `dir/*` globs. */
export function workspacePackages(root = ROOT) {
  const yaml = readFileSync(join(root, 'pnpm-workspace.yaml'), 'utf8');
  const globs = [...yaml.matchAll(/^\s*-\s*['"]?([^'"\s]+)['"]?\s*$/gm)].map((m) => m[1]);
  if (!globs.length) fail('pnpm-workspace.yaml lists no packages');
  return globs.flatMap((g) => {
    if (!/^[\w.-]+\/\*$/.test(g)) fail(`pnpm-workspace.yaml glob "${g}" is not of the form dir/* this reads`);
    const parent = g.slice(0, -2);
    return readdirSync(join(root, parent)).map((d) => `${parent}/${d}`).filter((d) => existsSync(join(root, d, 'package.json'))).sort();
  });
}

/** The esbuild flags a bundle's build may use. Any other flag is refused rather than ignored,
 *  because a metafile built without it could describe a different bundle from the one shipped. */
const BUNDLE_FLAGS = new Set(['bundle', 'format', 'target', 'legal-comments', 'outfile']);

/**
 * Every esbuild command, in every workspace package, whose output lands in `apps/web/vendor/`:
 * `{ pkg, entry, bundle, format, target }`. Read from the package scripts that build them, so the
 * notices describe exactly the builds CI checks for drift.
 */
export function bundleBuilds(root = ROOT) {
  const vendor = join(root, 'apps/web/vendor');
  const out = [];
  for (const pkg of workspacePackages(root)) {
    const scripts = JSON.parse(readFileSync(join(root, pkg, 'package.json'), 'utf8')).scripts ?? {};
    for (const cmd of Object.values(scripts)) {
      for (const step of String(cmd).split('&&').map((s) => s.trim()).filter((s) => s.startsWith('esbuild '))) {
        const words = step.split(/\s+/).slice(1);
        const entry = words.find((w) => !w.startsWith('--'));
        const flags = Object.fromEntries(words.filter((w) => w.startsWith('--')).map((w) => {
          const [k, ...v] = w.slice(2).split('=');
          return [k, v.length ? v.join('=') : true];
        }));
        if (typeof flags.outfile !== 'string' || dirname(resolve(root, pkg, flags.outfile)) !== vendor) continue;
        const unknown = Object.keys(flags).filter((k) => !BUNDLE_FLAGS.has(k));
        if (unknown.length) fail(`${pkg}: "${step}" uses esbuild flags this cannot reproduce: ${unknown.join(', ')}`);
        if (flags.bundle !== true || !entry) fail(`${pkg}: "${step}" is not a single-entry bundle`);
        out.push({ pkg, entry, bundle: basename(flags.outfile), format: flags.format, target: flags.target });
      }
    }
  }
  if (!out.length) fail('no esbuild step writes into apps/web/vendor/ — the script scan is broken');
  return out.sort((a, b) => a.bundle.localeCompare(b.bundle));
}

/** The package a file belongs to: the directory after its LAST `node_modules/`, or null. */
function packageOf(file) {
  const m = /^(.*[/\\]node_modules[/\\](?:@[^/\\]+[/\\])?[^/\\]+)[/\\]/.exec(file);
  if (!m) return null;
  const pkg = JSON.parse(readFileSync(join(m[1], 'package.json'), 'utf8'));
  if (!pkg.name || !pkg.version) fail(`${m[1]}/package.json has no name or version`);
  return { dir: m[1], name: pkg.name, version: pkg.version, pkg };
}

/**
 * The third-party packages whose code is IN a bundle: every metafile input under node_modules that
 * contributes at least one byte of output. A package imported and entirely tree-shaken away ships
 * nothing and is not listed; a package a dependency pulls in ships and is.
 */
export function packagesInBundle(root, build) {
  // This repository's esbuild, whichever tree is being scanned: the one the bundles are built with.
  const { buildSync } = createRequire(join(ROOT, 'apps/web/package.json'))('esbuild');
  const cwd = join(root, build.pkg);
  const result = buildSync({
    absWorkingDir: cwd, entryPoints: [build.entry], bundle: true, write: false, metafile: true,
    format: build.format, target: build.target, outfile: join(cwd, 'notices-probe.js'), logLevel: 'silent',
  });
  const outputs = Object.values(result.metafile.outputs);
  if (outputs.length !== 1) fail(`${build.bundle}: expected one output, esbuild produced ${outputs.length}`);
  const found = new Map();
  for (const [input, { bytesInOutput }] of Object.entries(outputs[0].inputs)) {
    if (!bytesInOutput) continue;
    const owner = packageOf(resolve(cwd, input));
    if (owner) found.set(`${owner.name}@${owner.version}`, owner);
  }
  return [...found.values()];
}

