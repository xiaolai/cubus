function cargo(root, args) {
  return execFileSync('cargo', args, { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 });
}

export function rustInventory(root = ROOT) {
  const meta = JSON.parse(cargo(root, ['metadata', '--format-version', '1', '--locked']));
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const members = new Set(meta.workspace_members.map((id) => byId.get(id).name));
  // Every crate the desktop binary links on ANY target — normal deps only: build scripts and
  // dev-deps are not in the shipped binary.
  const tree = cargo(root, ['tree', '--target', 'all', '-e', 'normal', '-p', 'cubus-desktop', '--prefix', 'none', '--locked']);
  const wanted = new Set();
  for (const line of tree.split('\n')) {
    const m = /^(\S+) v(\S+)/.exec(line.trim());
    if (m) wanted.add(`${m[1]} ${m[2]}`);
  }
  const crates = meta.packages
    .filter((p) => wanted.has(`${p.name} ${p.version}`) && !members.has(p.name))
    .map((p) => {
      if (!p.license) fail(`${p.name} ${p.version} declares no license expression (license_file: ${p.license_file ?? 'none'})`);
      const dir = dirname(p.manifest_path);
      return {
        name: p.name,
        version: p.version,
        expr: p.license,
        authors: (p.authors ?? []).map((a) => a.replace(/\s*<[^>]*>/g, '').trim()).filter(Boolean),
        repo: p.repository ?? `https://crates.io/crates/${p.name}`,
        dir,
        files: licenceFilesIn(dir, p.license_file ? [p.license_file] : []),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  if (crates.length < 100) fail(`only ${crates.length} crates found — the tree walk is broken`);
  // The ONNX Runtime the `ort` crate downloads prebuilt for the native scanner: its release,
  // read from the download table ort-sys builds from, so the right notices file is named.
  const ortSys = crates.find((c) => c.name === 'ort-sys');
  let ortNative = null;
  if (ortSys) {
    const table = readFileSync(join(ortSys.dir, 'build', 'download', 'dist.tsv'), 'utf8');
    const releases = [...new Set([...table.matchAll(/\/ms@(\d+\.\d+\.\d+)\//g)].map((m) => m[1]))];
    if (releases.length !== 1) fail(`ort-sys ${ortSys.version}'s dist.tsv names ${releases.length} ONNX Runtime releases (${releases.join(', ')}), not one`);
    ortNative = releases[0];
  }
  return { crates, members: [...members].sort(), ortNative };
}

