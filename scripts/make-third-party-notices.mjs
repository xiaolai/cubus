const text = render();
if (process.argv.includes('--check')) {
  let committed = '';
  try { committed = readFileSync(OUT, 'utf8'); } catch { /* absent counts as drifted */ }
  if (committed !== text) {
    console.error(`${OUT} is not what would be generated from the current lockfiles and packages — run \`pnpm notices\` and commit the result.`);
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is current.');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.split('\n').length} lines)`);
}
