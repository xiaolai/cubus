// 3. The Android shell's libraries: the release runtime classpath Gradle resolved and locked.

const ANDROID = 'apps/desktop/src-tauri/gen/android/app';

/**
 * The coordinates of every external module on the app's release runtime classpaths, from the
 * Gradle lockfile the build enforces (`dependencyLocking` in app/build.gradle.kts). Reading the
 * `implementation(...)` lines instead, as this once did, saw only what one file declared: nothing
 * a Tauri plugin module brings (jackson-databind, androidx.browser), nothing transitive, and
 * declared versions rather than resolved ones.
 */
export function androidLockedModules(lockfileText) {
  const modules = new Set();
  let release = 0;
  for (const line of lockfileText.split('\n')) {
    const m = /^([^#=\s][^=\s]*):([^:=\s]+):([^:=\s]+)=(.*)$/.exec(line.trim());
    if (!m) continue;
    const configs = m[4].split(',');
    if (configs.some((c) => /ReleaseRuntimeClasspath$/.test(c))) { modules.add(`${m[1]}:${m[2]}:${m[3]}`); release++; }
  }
  if (!release) fail('the Android lockfile locks no *ReleaseRuntimeClasspath module — is dependency locking still on?');
  return [...modules].sort();
}

/**
 * POM licence declarations to the SPDX id they mean. A name that says too little on its own is read
 * with the URL it points at: camera-core's "BSD License" is libyuv's, which is BSD-3-Clause.
 */
const POM_LICENCES = [
  (l) => /^(?:the )?apache(?: software)? license,? (?:version )?2\.0$|^apache[- ]2\.0$/i.test(l.name) && 'Apache-2.0',
  (l) => /^(?:the )?mit license$|^mit$/i.test(l.name) && 'MIT',
  (l) => /^bsd license$/i.test(l.name) && /^https:\/\/chromium\.googlesource\.com\/libyuv\//.test(l.url ?? '') && 'BSD-3-Clause',
];

/**
 * Every locked release module: `{ coord, expr, urls, files }`, `files` null for a module nothing of
 * which is packaged. EVERY licence a POM lists applies. Maven's own reference calls several a
 * choice, but camera-core lists libyuv's BSD licence beside its Apache one because it contains
 * libyuv — a notice that honours both is right under either reading, and one that picks is not.
 */
export function androidInventory(root = ROOT) {
  const locked = androidLockedModules(readFileSync(join(root, ANDROID, 'gradle.lockfile'), 'utf8'));
  const { modules, texts } = JSON.parse(readFileSync(join(root, ANDROID, 'dependency-licences.json'), 'utf8'));
  const rerun = '— run scripts/android-licences.mjs';
  const stale = Object.keys(modules).filter((k) => !locked.includes(k));
  if (stale.length) fail(`dependency-licences.json describes modules the lockfile no longer has: ${stale.join(', ')} ${rerun}`);
  for (const [sha, text] of Object.entries(texts)) {
    if (createHash('sha256').update(text).digest('hex') !== sha) fail(`dependency-licences.json holds a text that does not hash to its key ${sha} ${rerun}`);
  }
  return locked.map((coord) => {
    const entry = modules[coord];
    if (!entry?.licenses?.length) fail(`Android module ${coord} has no licence in dependency-licences.json ${rerun}`);
    const ids = entry.licenses.map((l) => POM_LICENCES.map((rule) => rule(l)).find(Boolean));
    const unknown = entry.licenses.filter((_, i) => !ids[i]).map((l) => `${l.name} <${l.url}>`);
    if (unknown.length) fail(`Android module ${coord} is licensed "${unknown.join('", "')}", which this does not map to an SPDX id — decide, then extend POM_LICENCES`);
    const files = entry.files === null ? null : entry.files.map(({ file, sha256 }) => {
      if (!Object.hasOwn(texts, sha256)) fail(`Android module ${coord}'s ${file} names a text dependency-licences.json does not hold ${rerun}`);
      return { file, text: texts[sha256] };
    });
    return { coord, expr: [...new Set(ids)].join(' AND '), urls: entry.licenses.map((l) => l.url).filter(Boolean), files };
  });
}

