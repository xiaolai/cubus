// 4. The model: what it was trained with, and on.
function modelAttribution(root) {
  const read = (p) => readFileSync(join(root, p), 'utf8');
  const card = read('ml/MODEL_CARD.md');
  // WHERE THE DETECTOR CAME FROM, read from the manifest the export writes rather than from prose.
  // This once read a pinned trainer version out of the model card, because the
  // shipped detector was trained with it; the sentence it parsed is gone with the lineage, and a
  // regex over a document is the wrong place to learn what a model is anyway.
  const manifest = JSON.parse(read('ml/models/MANIFEST.json'));
  const provenance = manifest.licence_note;
  if (!provenance) fail('ml/models/MANIFEST.json carries no licence_note — re-run ml/export.py');
  if (manifest.stack !== 'cubedet') {
    fail(`ml/models/MANIFEST.json says the shipped model was built by ${manifest.stack}; this file describes cubedet's`);
  }
  const rows = [...card.matchAll(/^\| `([^`/]+)\/([^`]+)` \| (https:\/\/universe\.roboflow\.com\/\S+) \| ([^|]+) \|$/gm)]
    .map((m) => ({ workspace: m[1], project: m[2], url: m[3], usedFor: m[4].trim() }));
  if (rows.length === 0) fail('no Roboflow attribution rows found in ml/MODEL_CARD.md');
  // Every dataset the fetcher downloads must be in the card's table, or the notice is short.
  const fetched = [...read('ml/fetch_roboflow.py').matchAll(/\("([^"]+)",\s*"([^"]+)"\)/g)].map((m) => `${m[1]}/${m[2]}`);
  for (const id of fetched) {
    if (!rows.some((r) => `${r.workspace}/${r.project}` === id)) fail(`ml/fetch_roboflow.py downloads ${id}, which ml/MODEL_CARD.md's attribution table does not list`);
  }
  const fixtures = JSON.parse(read('ml/golden/SOURCES.json')).filter((e) => /^https?:\/\//.test(e.source));
  return { provenance, backbone: manifest.backbone, rows, fixtures };
}

// ---------------------------------------------------------------------------------------------
// ONNX Runtime's own notices, for the releases that ship.

/**
 * Microsoft's ThirdPartyNotices.txt for each ONNX Runtime release a build ships, by sha256 of the
 * file at that release's tag. The web app ships the release onnxruntime-web was built from; the
 * Windows scanner ships the one `ort-sys` downloads. A release that ships with no pin here, a file
 * that does not hash to its pin, or a file for a release nothing ships, stops the run.
 */
export const ORT_NOTICE_PINS = Object.freeze({
  '1.28.0': '0e07b95f3a8d6230037707c5c4a2b554d12c4cb67369669ac255635528ffcee2',
  '1.29.0': '53d3fa5821ac016ac24dd35775c996efec86e2ae0841e9a3a5e146c0ae916845',
});
export const ORT_NOTICES_DIR = 'apps/web/notices';
export const ortNoticesFile = (release) => `onnxruntime-${release}-ThirdPartyNotices.txt`;
const ortNoticesSource = (release) => `https://github.com/microsoft/onnxruntime/blob/v${release}/ThirdPartyNotices.txt`;

export function checkOrtNotices(root, releases, pins = ORT_NOTICE_PINS) {
  const dir = join(root, ORT_NOTICES_DIR);
  const want = [...new Set(releases)].sort().map(ortNoticesFile);
  const have = existsSync(dir) ? readdirSync(dir).sort() : [];
  const stale = have.filter((f) => !want.includes(f));
  if (stale.length) fail(`${ORT_NOTICES_DIR}/ holds notices for a release nothing ships: ${stale.join(', ')} — delete them`);
  for (const release of [...new Set(releases)].sort()) {
    const file = ortNoticesFile(release);
    if (!have.includes(file)) fail(`ONNX Runtime ${release} ships and ${ORT_NOTICES_DIR}/${file} is missing — fetch it from ${ortNoticesSource(release)} (raw) and pin its sha256 in ORT_NOTICE_PINS`);
    const digest = createHash('sha256').update(readFileSync(join(dir, file))).digest('hex');
    if (!Object.hasOwn(pins, release)) fail(`ONNX Runtime ${release}'s notices are not pinned — add ${digest} to ORT_NOTICE_PINS after checking it against ${ortNoticesSource(release)}`);
    if (pins[release] !== digest) fail(`${ORT_NOTICES_DIR}/${file} hashes to ${digest}, not its pin ${pins[release]} — it is not the file published at ${ortNoticesSource(release)}`);
  }
}

