/** The runtime copy-ort.mjs publishes into vendor/: which package it is, and what it copies. */
async function copiedRuntime(root) {
  const { ORT_SOURCE, ORT_ESM, ORT_PROXIED, ownedAssetsIn } = await import(pathToFileURL(join(root, 'apps/web/copy-ort.mjs')).href);
  const dir = dirname(ORT_SOURCE);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const assets = ownedAssetsIn(readFileSync(join(ORT_SOURCE, ORT_ESM), 'utf8')).sort();
  return { dir, name: pkg.name, version: pkg.version, pkg, files: ['ort.mjs', ORT_PROXIED, ...assets] };
}

/**
 * Every npm package that ships in the web app, with the bundles it is in; and the packages that
 * are bundled only into something build.mjs never ships.
 */
export async function npmInventory(root = ROOT) {
  const { NEVER_SHIPPED } = await import(pathToFileURL(join(root, 'apps/web/build.mjs')).href);
  const shipped = new Map();
  const unshipped = new Map();
  for (const build of bundleBuilds(root)) {
    if (!Object.hasOwn(BUNDLE_ROLES, build.bundle)) fail(`vendor/${build.bundle} has no entry in BUNDLE_ROLES — say what it is for`);
    const target = NEVER_SHIPPED.includes(`vendor/${build.bundle}`) ? unshipped : shipped;
    for (const p of packagesInBundle(root, build)) {
      const key = `${p.name}@${p.version}`;
      if (!target.has(key)) target.set(key, { ...p, bundles: [] });
      target.get(key).bundles.push(build.bundle);
    }
  }
  const runtime = await copiedRuntime(root);
  const key = `${runtime.name}@${runtime.version}`;
  shipped.set(key, { ...(shipped.get(key) ?? runtime), bundles: shipped.get(key)?.bundles ?? [], copied: runtime.files });
  const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version);
  const shippedList = [...shipped.values()].sort(byName);
  for (const u of unshipped.values()) {
    if (shipped.has(`${u.name}@${u.version}`)) unshipped.delete(`${u.name}@${u.version}`);
  }
  return { shipped: shippedList, unshipped: [...unshipped.values()].sort(byName) };
}

/** A package.json's repository and author, as a reader would want them. */
function npmMeta(pkg) {
  // Without the address or homepage an author string may carry — the same as a crate's authors.
  const author = (typeof pkg.author === 'string' ? pkg.author : pkg.author?.name)
    ?.replace(/\s*<[^>]*>|\s*\([^)]*\)/g, '').replace(/\.$/, '').trim();
  const repo = (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '')
    .replace(/^git\+/, '').replace(/\.git$/, '');
  return { author, repo };
}

