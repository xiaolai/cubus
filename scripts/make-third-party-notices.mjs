// Licence expressions.

/**
 * The licences this project accepts a dependency under, most preferred first.
 *
 * IJG (the Independent JPEG Group licence, mozjpeg) and CDLA-Permissive-2.0 (webpki-root-certs'
 * certificate data) are permissive attribution licences with no OR alternative in the tree; they
 * sit last so they are chosen only when nothing above them is offered.
 */
export const PREFERENCE = Object.freeze([
  'MIT', 'Apache-2.0', 'BSD-3-Clause', 'BSD-2-Clause', 'ISC', 'Zlib', 'Unicode-3.0', '0BSD', 'MIT-0',
  'Unlicense', 'CC0-1.0', 'MPL-2.0', 'IJG', 'CDLA-Permissive-2.0',
]);

/** Exceptions accepted with a licence: each only ADDS a permission to the licence it modifies. */
export const EXCEPTIONS = Object.freeze(['LLVM-exception']);

/**
 * Parse an SPDX licence expression into a tree of `{ or }`, `{ and }` and `{ licence, exception }`.
 *
 * SPDX 2.3 Annex D precedence: WITH binds tighter than AND, and AND tighter than OR. Cargo's
 * legacy `/` separator means OR. Splitting on the words, as this file once did, turned
 * `MIT OR (Apache-2.0 AND GPL-3.0-only)` into a refusal and `Apache-2.0 WITH X` into plain
 * Apache-2.0 whatever X was.
 */
export function parseSpdx(expr) {
  const tokens = String(expr).replace(/\//g, ' OR ').match(/\(|\)|[^\s()]+/g) ?? [];
  let i = 0;
  const is = (t, word) => typeof t === 'string' && t.toUpperCase() === word;
  const refuse = (why) => fail(`"${expr}" is not a licence expression: ${why}`);
  const id = (t) => typeof t === 'string' && /^[A-Za-z0-9][A-Za-z0-9.+-]*$/.test(t) && !['AND', 'OR', 'WITH'].some((w) => is(t, w));
  const atom = () => {
    const t = tokens[i++];
    if (t === '(') {
      const inner = or();
      if (tokens[i++] !== ')') refuse('a parenthesis is not closed');
      return inner;
    }
    if (!id(t)) refuse(t === undefined ? 'it ends where a licence was expected' : `"${t}" stands where a licence was expected`);
    return { licence: t };
  };
  const withTerm = () => {
    const node = atom();
    if (!is(tokens[i], 'WITH')) return node;
    i++;
    if (!node.licence) refuse('WITH follows a group, not a licence');
    const ex = tokens[i++];
    if (!id(ex)) refuse('WITH names no exception');
    return { licence: node.licence, exception: ex };
  };
  const and = () => {
    const terms = [withTerm()];
    while (is(tokens[i], 'AND')) { i++; terms.push(withTerm()); }
    return terms.length === 1 ? terms[0] : { and: terms };
  };
  const or = () => {
    const terms = [and()];
    while (is(tokens[i], 'OR')) { i++; terms.push(and()); }
    return terms.length === 1 ? terms[0] : { or: terms };
  };
  const tree = or();
  if (i !== tokens.length) refuse(`"${tokens[i]}" follows a complete expression`);
  return tree;
}

const termName = (t) => (t.exception ? `${t.licence} WITH ${t.exception}` : t.licence);

/** Every way to comply with an expression tree: alternatives, each the list of terms it binds. */
export function alternatives(tree) {
  if (tree.or) return tree.or.flatMap(alternatives);
  if (tree.and) {
    return tree.and
      .map(alternatives)
      .reduce((acc, next) => acc.flatMap((a) => next.map((b) => [...a, ...b])), [[]])
      .map((terms) => [...new Map(terms.map((t) => [termName(t), t])).values()]);
  }
  return [[tree]];
}

/**
 * The terms `expr` is used under, or null when no alternative is accepted.
 *
 * An alternative is accepted when every term is: its licence in `preference`, its exception (if
 * any) in `exceptions`. Among accepted ones, the fewest terms whose text the package does NOT
 * carry wins — `carried` is the licences identified in its own files — then the best-preferred,
 * then the shortest. Used under a licence whose text it ships, a package's notice is its own.
 */
export function chooseLicences(expr, { preference = PREFERENCE, exceptions = EXCEPTIONS, carried = [] } = {}) {
  const rank = (t) => preference.indexOf(t.licence);
  const accepted = (t) => rank(t) >= 0 && (t.exception === undefined || exceptions.includes(t.exception));
  const options = alternatives(parseSpdx(expr)).filter((alt) => alt.every(accepted));
  if (!options.length) return null;
  const uncarried = (alt) => alt.filter((t) => !carried.includes(t.licence)).length;
  const ranks = (alt) => alt.map(rank).sort((a, b) => a - b);
  const byRank = (a, b) => {
    const [ra, rb] = [ranks(a), ranks(b)];
    for (let j = 0; j < Math.min(ra.length, rb.length); j++) if (ra[j] !== rb[j]) return ra[j] - rb[j];
    return ra.length - rb.length;
  };
  return [...options].sort((a, b) => uncarried(a) - uncarried(b) || byRank(a, b))[0].map(termName);
}

// ---------------------------------------------------------------------------------------------
// Licence and notice files.

/** A file a package's licence or notices live in. `.spdx` is a document ABOUT a licence. */
const LICENCE_FILE = /^(?:LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)(?:[-_.][\w.-]*)?$/i;
const NOT_A_LICENCE = /\.spdx$/i;
/** Kept whatever it says: Apache-2.0 §4(d) makes a NOTICE file's contents an obligation. */
const NOTICE_FILE = /^(?:NOTICE|COPYRIGHT)/i;

const ISC_GRANT = /permission to use, copy, modify,? and\/or distribute this software for any purpose with or without fee is hereby granted/;
const MIT_GRANT = /permission is hereby granted, free of charge, to any person obtaining a copy/;

/**
 * Which licences a text IS, by the phrases that define each — never by its filename, which is
 * how a BSD text named LICENSE gets filed as whatever the package's first alternative is.
 * GPL-family texts are recognised so that a package offering one as an unused alternative has
 * that file left out rather than kept as unrecognised.
 */
export const LICENCE_MARKS = Object.freeze({
  // Each by the sentence that makes it what it is, not by a phrase the other lacks: MIT grants
  // "subject to the following conditions", MIT-0 grants and goes straight to the warranty.
  // Keyed on one condition's exact wording, bytemuck's X11-worded MIT read as MIT-0.
  'MIT': (t) => MIT_GRANT.test(t) && /furnished to do so, subject to the following conditions/.test(t),
  'MIT-0': (t) => MIT_GRANT.test(t) && /furnished to do so\. the software is provided/.test(t),
  'Apache-2.0': (t) => /apache license,? version 2\.0/.test(t) && /terms and conditions for use, reproduction,? and distribution/.test(t),
  'BSD-3-Clause': (t) => /redistribution and use in source and binary forms/.test(t) && /neither the name|names of (?:its|the) contributors may (?:not )?be used/.test(t),
  'BSD-2-Clause': (t) => /redistribution and use in source and binary forms/.test(t) && !/neither the name|names of (?:its|the) contributors may (?:not )?be used/.test(t),
  'ISC': (t) => ISC_GRANT.test(t) && /hereby granted, provided that the above copyright notice/.test(t),
  '0BSD': (t) => ISC_GRANT.test(t) && /hereby granted\. the software is provided/.test(t),
  'Zlib': (t) => /this software is provided ['‘’]as-is['‘’], without any express or implied warranty/.test(t),
  'Unicode-3.0': (t) => /unicode license v3/.test(t),
  'Unlicense': (t) => /this is free and unencumbered software released into the public domain/.test(t),
  'CC0-1.0': (t) => /cc0 1\.0 universal/.test(t),
  'MPL-2.0': (t) => /mozilla public license,? version 2\.0/.test(t),
  'IJG': (t) => /independent jpeg group/.test(t),
  'CDLA-Permissive-2.0': (t) => /community data license agreement\s*[-–—]?\s*permissive\s*[-–—]?\s*version 2\.0/.test(t),
  // By the title line, dated: the MPL-2.0 text names "the GNU Lesser General Public License,
  // Version 2.1" in its definitions, and a mark on the name alone read every MPL text as LGPL too.
  'LGPL': (t) => /gnu lesser general public license version (?:2\.1, february 1999|3, 29 june 2007)/.test(t),
  'GPL': (t) => /gnu general public license version (?:2, june 1991|3, 29 june 2007)/.test(t),
});

export const identifyLicences = (text) => {
  // Comment markers off first: `untrusted` ships its ISC text as `//` lines, and
  // "for any // purpose" matches no licence's wording.
  const t = text.replace(/^[ \t]*(?:\/\/+|#+|\*+|;+)[ \t]?/gm, '').toLowerCase().replace(/\s+/g, ' ');
  return Object.keys(LICENCE_MARKS).filter((id) => LICENCE_MARKS[id](t));
};

/** A text as compared and printed: LF line ends, no trailing blanks, no BOM, no edge lines. */
export const normaliseText = (text) => text.replace(/^﻿/, '').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').replace(/^\n+|\n+$/g, '');

/** The licence and notice files directly in `dir`, plus Cargo's `license_file` if it names one. */
export function licenceFilesIn(dir, extra = []) {
  const names = readdirSync(dir).filter((f) => LICENCE_FILE.test(f) && !NOT_A_LICENCE.test(f) && statSync(join(dir, f)).isFile());
  return [...new Set([...names, ...extra])].sort().map((file) => ({ file, text: normaliseText(readFileSync(join(dir, file), 'utf8')) }));
}

/**
 * Which of a package's files travel with it, given the licences it is used under.
 *
 * Kept: every notice file; every file identified as one of `under`; and every file that cannot be
 * identified at all, because a text nobody recognised may still carry an obligation. Left out: a
 * file identified ONLY as licences the package is not used under — the Apache text of a crate used
 * under MIT. Returns what was kept and which of `under` those files cover.
 */
export function selectLicenceFiles(files, under) {
  const bases = under.map((u) => u.replace(/ WITH .*$/, ''));
  const kept = [];
  const covered = new Set();
  for (const f of files) {
    if (!f.text) continue;
    if (NOTICE_FILE.test(f.file)) { kept.push(f); continue; }
    const ids = identifyLicences(f.text);
    const used = ids.filter((id) => bases.includes(id));
    if (used.length) { used.forEach((id) => covered.add(id)); kept.push(f); } else if (!ids.length) kept.push(f);
  }
  return { kept, covered: bases.filter((b) => covered.has(b)) };
}

/**
 * One entry per distinct text, each with every carrier. Ids are the text's hash, so adding a
 * dependency never renumbers the texts already listed and a regenerated file diffs to what moved.
 */
export function textTable(carriers) {
  const byText = new Map();
  for (const { owner, file, text } of carriers) {
    if (!byText.has(text)) byText.set(text, { id: `text-${createHash('sha256').update(text).digest('hex').slice(0, 12)}`, text, carriers: [] });
    byText.get(text).carriers.push(`${owner} (\`${file}\`)`);
  }
  const ids = new Set();
  for (const e of byText.values()) {
    if (ids.has(e.id)) fail(`two different texts share the id ${e.id}`);
    ids.add(e.id);
  }
  return byText;
}

