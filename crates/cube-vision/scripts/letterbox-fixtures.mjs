// The TypeScript letterbox's answer for the Rust parity fixtures (2026-09-21, audit-fix row 38).
//
// `crates/cube-vision/src/letterbox.rs` claims to reproduce `preprocess()` from
// `packages/cube-scanner/src/letterbox.ts` byte for byte; its test compares an FNV-1a 64 hash of
// every output float (little-endian bytes) against the numbers this script prints, and this script
// is the ONLY place those numbers come from — the reference implementation, not the Rust. Run it
// from the repo root after any change to either letterbox:
//
//   node crates/cube-vision/scripts/letterbox-fixtures.mjs
//
// The fixture pixels are generated by the same formula as `fixture()` in letterbox.rs, so the two
// sides hash the same picture. Needs the scanner package's esbuild (`pnpm install`).

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '../../..');
const SCANNER = join(ROOT, 'packages/cube-scanner');
const scratch = mkdtempSync(join(tmpdir(), 'letterbox-fixtures-'));
const bundle = join(scratch, 'letterbox.mjs');
execFileSync(join(SCANNER, 'node_modules/.bin/esbuild'), [
  join(SCANNER, 'src/letterbox.ts'), '--bundle', '--format=esm', '--platform=node', `--outfile=${bundle}`,
], { stdio: ['ignore', 'ignore', 'inherit'] });
const { preprocess } = await import(pathToFileURL(bundle).href);

/** The same picture `letterbox.rs`'s `fixture(w, h)` makes, as RGBA. */
function fixture(w, h) {
  const data = new Uint8ClampedArray(w * h * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      data[o] = (x * 7 + y * 13) % 256;
      data[o + 1] = (x * 31 + y * 5 + 77) % 256;
      data[o + 2] = (x * 17 + y * 23 + 191) % 256;
      data[o + 3] = 255;
    }
  }
  return { data, width: w, height: h };
}

/** FNV-1a 64 over the little-endian bytes of every float, as `letterbox.rs` computes it. */
function fnv1a64(floats) {
  const bytes = new Uint8Array(floats.length * 4);
  const view = new DataView(bytes.buffer);
  floats.forEach((v, i) => view.setFloat32(i * 4, v, true));
  let h = 0xcbf29ce484222325n;
  const prime = 0x100000001b3n;
  const mask = (1n << 64n) - 1n;
  for (const b of bytes) {
    h ^= BigInt(b);
    h = (h * prime) & mask;
  }
  return h;
}

const SHAPES = [[97, 43], [43, 97], [50, 50], [1, 1], [640, 1], [1, 640], [1281, 721], [3, 1000]];
for (const [w, h] of SHAPES) {
  const { data } = preprocess(fixture(w, h));
  console.log(`(${w}, ${h}, 0x${fnv1a64(data).toString(16).padStart(16, '0')}),`);
}
rmSync(scratch, { recursive: true, force: true });
